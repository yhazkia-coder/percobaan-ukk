class Book {
  final String id;
  final String title;
  final String author;
  final String category;
  final String synopsis;
  final int stock;
  final String imageUrl;

  Book({
    required this.id,
    required this.title,
    required this.author,
    required this.category,
    required this.synopsis,
    required this.stock,
    required this.imageUrl,
  });
}
